# -*- coding: utf-8 -*-
"""2차 검산 (2차에서 새로 만든 스크립트. 1차에는 없음): 마을 '등불골' 좌표와 걷는 시간.
마을 84x48유닛, 마을 길 이동 속도 초당 6.5 고정. 길은 마당 -> 장터 광장 (42,29) 경유, 훈련장은 마당 동쪽 문 (56,40) 근처 울타리 입구 (58,40) 방향.
실행: python fin_town_walk.py"""
import math, sys, io
if (sys.stdout.encoding or "").lower() != "utf-8":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
V = 6.5
P = {"귀환 지점": (42, 41), "갱도 입구": (42, 45), "대장간 모루": (34, 38), "창고 문": (50, 38), "의뢰 게시판": (36, 26), "상점 가판": (48, 26),
     "훈련장 허수아비": (64, 40), "등불 언덕 사당": (12, 24), "마을 입구(시작 지점)": (84, 24), "장터 광장": (42, 29)}
VIA = {"의뢰 게시판": ["장터 광장"], "상점 가판": ["장터 광장"], "등불 언덕 사당": ["장터 광장"], "마을 입구(시작 지점)": ["장터 광장"]}
def d(a, b): return math.dist(P[a], P[b])
def path(a, b):
    pts = [a] + VIA.get(b, []) + [b]
    return sum(d(pts[i], pts[i + 1]) for i in range(len(pts) - 1))
print("| 장소 | 좌표 | 귀환 지점에서 거리 | 걷는 시간 |")
print("|---|---|---|---|")
for k in ["갱도 입구", "대장간 모루", "창고 문", "의뢰 게시판", "상점 가판", "훈련장 허수아비", "등불 언덕 사당", "마을 입구(시작 지점)"]:
    L = path("귀환 지점", k); print(f"| {k} | {P[k]} | {L:.1f} | {L / V:.1f}초 |")
core = d("귀환 지점", "대장간 모루") + d("대장간 모루", "갱도 입구"); print(f"\n핵심 순환 귀환 -> 대장간 -> 갱도 입구: {core:.1f}유닛, {core / V:.1f}초")
tour = ["귀환 지점", "창고 문", "대장간 모루", "장터 광장", "의뢰 게시판", "상점 가판", "장터 광장", "귀환 지점", "훈련장 허수아비", "갱도 입구"]
L = sum(d(tour[i], tour[i + 1]) for i in range(len(tour) - 1)); print(f"모든 시설 한 바퀴(귀환 -> 창고 -> 대장간 -> 게시판 -> 상점 -> 허수아비 -> 입구): {L:.1f}유닛, {L / V:.1f}초")
lam = 2 * d("장터 광장", "등불 언덕 사당"); print(f"등불 언덕 사당에 들를 때 더 드는 시간(광장 <-> 사당 왕복): {lam:.1f}유닛, {lam / V:.1f}초")
print(f"마을 넓이 84x48 = {84 * 48}, 큰 전투방 26x14 = {26 * 14}, {84 * 48 / (26 * 14):.1f}배")
print(f"카메라 크기 8.0에서 16:9 화면에 보이는 범위: 가로 {8.0 * 2 * 16 / 9:.1f} x 세로 16.0")
print("귀환할 때 카메라 중심 (42, 40): 보이는 범위 x 27.8~56.2, y 32~48 = 갱도 마당 한 화면(귀환 지점, 갱도 입구와 등불 줄 12개, 대장간, 창고)")

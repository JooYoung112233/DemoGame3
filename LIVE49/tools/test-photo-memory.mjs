import assert from'node:assert/strict';
import{PHOTO,photoFrame}from'../design/ui/ch00-01/photo-memory.mjs';
let count=0;function ok(v){assert.ok(v);count++;}
ok(photoFrame('photo-entry',0).opacity===0);
